        <h1>Qué exige la Ley 21.442 a las administradoras de condominios en Chile</h1>
        <p class="meta">Actualizado 2026 · Lectura de 6 minutos</p>

        <p>
            La Ley 21.442, que reemplazó a la antigua Ley 19.537 sobre Copropiedad Inmobiliaria, cambió de forma
            concreta cómo debe operar quien administra un condominio o edificio en Chile. No es solo un cambio de
            número de ley: introdujo obligaciones de registro, transparencia financiera y formalidad documental que
            antes eran prácticas recomendadas y hoy son exigencias con respaldo legal. Esta guía resume, en términos
            operativos, qué implica para quien administra día a día.
        </p>

        <h2>1. Registro Nacional de Administradores de Condominios</h2>
        <p>
            La ley formalizó la figura del administrador profesional: quienes ejercen esta función a honorarios deben
            cumplir requisitos de habilitación e inscripción, lo que eleva el estándar frente al modelo anterior, donde
            cualquier persona podía asumir el cargo sin acreditación. Para una administradora que gestiona varias
            comunidades, esto significa que la trazabilidad de quién firma qué documento —y con qué respaldo— pasa a
            ser información que puede ser solicitada.
        </p>

        <h2>2. Fondo de reserva obligatorio</h2>
        <p>
            A diferencia del régimen anterior, donde el fondo de reserva era optativo en muchos casos, la nueva ley
            establece la obligación de mantener un fondo destinado a imprevistos y mantenciones mayores, calculado
            como parte del presupuesto de gastos comunes. El porcentaje y la forma de cálculo exactos están definidos
            en el reglamento vigente — conviene revisarlos directamente en la fuente oficial antes de fijar el
            presupuesto anual, ya que son parámetros que se pueden actualizar.
        </p>

        <h2>3. Rendición de cuentas y transparencia financiera</h2>
        <p>
            Se refuerzan los plazos y la formalidad para rendir cuentas ante la asamblea de copropietarios: libro de
            actas, acceso de los copropietarios a la información financiera de su comunidad, y respaldo documental de
            cada gasto. En la práctica, esto empuja a las administradoras a dejar de operar con planillas sueltas y
            adoptar un registro auditable, con bitácora de cada movimiento y conciliación bancaria verificable —no
            porque sea buena práctica, sino porque puede ser exigido.
        </p>

        <h2>4. Asambleas: quórum y modalidades</h2>
        <p>
            La ley actualizó las reglas de citación, quórum y modalidad de las asambleas de copropietarios, incluyendo
            la posibilidad de sesiones no estrictamente presenciales en ciertos casos. Esto obliga a documentar de
            forma más precisa las citaciones, la asistencia y los acuerdos adoptados, especialmente en comunidades
            grandes o multi-torre donde coordinar una asamblea presencial es logísticamente complejo.
        </p>

        <h2>5. Cobro de gastos comunes morosos</h2>
        <p>
            Se reforzaron los mecanismos de cobro frente a la morosidad, incluyendo reglas sobre intereses y vías de
            cobro más expeditas que antes. Esto exige a la administradora mantener un historial de pagos y moras
            impecable —fechas, montos, notificaciones enviadas— porque ese historial es lo que sostiene cualquier
            acción de cobro posterior.
        </p>

        <h2>6. Actualización del reglamento de copropiedad</h2>
        <p>
            Las comunidades constituidas bajo la ley anterior deben adecuar su reglamento interno a las nuevas
            disposiciones. Es un trabajo administrativo puntual, pero que suele quedar pendiente si no hay quien lo
            impulse activamente en la asamblea.
        </p>

        <h2>Lo que esto significa en la práctica</h2>
        <p>
            Ninguno de estos puntos es exótico por sí solo. Lo que cambió es que ahora hay una expectativa legal
            explícita de que la administración de un condominio se documente, se audite y se pueda revisar. Eso
            favorece claramente a quienes ya trabajan con un sistema que registra cada movimiento —gastos comunes,
            conciliación bancaria, actas de asamblea, bitácora de auditoría— frente a quienes siguen operando con
            planillas y carpetas físicas.
        </p>

