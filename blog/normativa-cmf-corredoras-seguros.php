        <h1>Qué debe cumplir una corredora de seguros regulada por la CMF en Chile</h1>
        <p class="meta">Actualizado 2026 · Lectura de 6 minutos</p>

        <p>
            En Chile, la actividad de intermediación de seguros está fiscalizada por la Comisión para el Mercado
            Financiero (CMF). Operar como corredora no es solo un tema comercial: implica un conjunto de obligaciones
            de registro, garantía y reporte que, si no se gestionan de forma ordenada, se vuelven un riesgo real
            frente a una fiscalización. Esta guía resume los puntos operativos más relevantes.
        </p>

        <h2>1. Inscripción en el Registro de Intermediarios de Seguros</h2>
        <p>
            Para operar legalmente, una corredora —y las personas naturales que actúan como corredores dentro de
            ella— debe estar inscrita en el Registro de Intermediarios de Seguros que administra la CMF. Es un
            requisito habilitante: sin inscripción vigente no hay intermediación legal posible, y la CMF puede
            verificar este estado en cualquier momento.
        </p>

        <h2>2. Garantía o póliza de responsabilidad civil</h2>
        <p>
            La normativa exige a los corredores mantener una garantía —históricamente boleta bancaria o póliza de
            responsabilidad civil— destinada a responder ante los asegurados por eventuales perjuicios derivados de
            su gestión. El monto y la forma exacta están definidos en la normativa vigente de la CMF, que conviene
            revisar directamente porque estos parámetros se actualizan.
        </p>

        <h2>3. Deberes de información frente al asegurado</h2>
        <p>
            Existe la obligación de entregar al cliente información clara sobre las condiciones de la póliza, las
            comisiones percibidas y cualquier conflicto de interés relevante —por ejemplo, vínculos con la aseguradora
            que se está ofreciendo. Esto es parte de las normas de conducta de mercado que la CMF exige a los
            intermediarios, orientadas a que el cliente tome una decisión informada.
        </p>

        <h2>4. Gestión de reclamos y trato justo</h2>
        <p>
            La corredora debe contar con un procedimiento para recibir y resolver reclamos de sus clientes, y estar
            en condiciones de acreditar cómo los gestionó si la CMF lo solicita. Un expediente de siniestro
            desordenado o incompleto no solo perjudica al cliente: es un problema documental frente a cualquier
            revisión.
        </p>

        <h2>5. Reporte periódico a la CMF</h2>
        <p>
            Las corredoras deben remitir información operacional y financiera de forma periódica al regulador. Cuanto
            más ordenada esté la cartera —pólizas vigentes, renovaciones, siniestros, comisiones— más simple es
            generar ese reporte sin trabajo manual de última hora.
        </p>

        <h2>6. Trazabilidad de endosos y comisiones</h2>
        <p>
            Cada modificación a una póliza (endoso) y cada comisión pagada —especialmente cuando se reparte entre la
            corredora y un vendedor— debe quedar registrada con historial verificable. No es solo buena práctica
            contable: es lo que permite reconstruir qué pasó con una póliza si un cliente o el regulador lo pregunta
            meses después.
        </p>

        <h2>7. Protección de datos personales</h2>
        <p>
            Una corredora administra información sensible de sus asegurados —datos de salud, patrimoniales,
            identificación. Con la entrada en vigencia de la nueva Ley de Protección de Datos Personales (Ley
            21.719), el estándar de cuidado sobre esa información —cifrado, control de acceso, trazabilidad de quién
            consulta qué— pasa de ser una buena práctica a una obligación legal explícita.
        </p>

